type MessageKey = keyof typeof messages.en;
type Translation = (typeof messages)[Locale];

export function isLocale(value: string | undefined): value is Locale {
  return locales.includes(value as Locale);
}

export function localeFromPath(pathname: string): Locale {
  const first = pathname.split("/").filter(Boolean)[0];
  return isLocale(first) ? first : "en";
}

export function localizedPath(pathname: string, locale: Locale) {
  const clean = pathname.startsWith("/") ? pathname : `/${pathname}`;
  return locale === "en" ? clean : `/${locale}${clean === "/" ? "" : clean}`;
}

export function switchLocalePath(pathname: string, locale: Locale) {
  const parts = pathname.split("/").filter(Boolean);
  if (isLocale(parts[0])) parts.shift();
  return localizedPath(`/${parts.join("/")}`, locale);
}

type I18nValue = {
  locale: Locale;
  t: (key: MessageKey) => string;
};

const I18nContext = createContext<I18nValue | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const pathname = useRouterState({ select: (state) => state.location.pathname });
  const locale = localeFromPath(pathname);
  const translation = messages[locale] as Partial<Record<MessageKey, string>>;
  const t = (key: MessageKey) => translation[key] ?? messages.en[key];

  return <I18nContext.Provider value={{ locale, t }}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const context = useContext(I18nContext);
  if (!context) throw new Error("useI18n must be used inside I18nProvider");
  return context;
}

export type { MessageKey, Translation };
