export function operatorStatus(status: "new" | "accepted" | "declined", c: Copy) {
  return status === "new"
    ? c.statusNew
    : status === "accepted"
      ? c.statusAccepted
      : c.statusDeclined;
}

export function localizedOperatorValue(value: string, c: Copy) {
  const map: Record<string, string> = {
    France: c.countryFrance,
    Germany: c.countryGermany,
    Ireland: c.countryIreland,
    "United Kingdom": c.countryUk,
    "Cabin motorboat": c.cabinMotorboat,
    Ready: c.ready,
    Maintenance: c.maintenance,
    "Custom private rental": c.customRental,
    "No booking": c.noBooking,
  };
  return map[value] ?? value;
}

export function operatorDate(value: string, locale: Locale, options?: Intl.DateTimeFormatOptions) {
  const parsed = /^([0-9]{1,2}) Aug 2026$/.exec(value);
  if (!parsed) return value;
  const day = parsed[1] ?? "1";
  return new Intl.DateTimeFormat(
    locale,
    options ?? { day: "numeric", month: "short", year: "numeric" },
  ).format(new Date(`2026-08-${day.padStart(2, "0")}T12:00:00Z`));
}

export function operatorRelativeTime(value: string, locale: Locale) {
  const match = /^(\d+) (min|hr)s? ago$/.exec(value);
  if (!match) return value;
  return new Intl.RelativeTimeFormat(locale, { numeric: "always" }).format(
    -Number(match[1]),
    match[2] === "min" ? "minute" : "hour",
  );
}
